# Common Functions(Applicable => 'strings', 'List', 'Set', 'Dictionary', 'Tupple')
# len, max, min, sorted

print(len('west bengal'))
print(max('west bengal'))       # In basis of ascii value
print(min('west bengal'))       # ' ' has min ascii value
print(sorted('west bengal'))
# sorted => gives output in 'List' at ascending order of ascii value of characters

print(sorted('west bengal', reverse = True))