# Arithmatic Operator
print(5 + 6)
print(5 - 6)
print(5 * 6)
print(5 / 2)            # Decimal Division
print(5 // 2)           # Integer Division
print(5 % 2)
print(5 ** 2)           # Power Operator

# Relational Operator
print(4 < 5)
print(4 > 5)
print(4 >= 4)
print(5 <= 5)
print(4 == 5)
print(4 != 5)

# Logical Operator
print(1 and 0)
print(1 or 0)
print(not 1)

# Bitwise Operator
print(2 & 3)        # Bitwise And
print(2 | 3)        # Bitwise Or
print(2 ^ 3)        # Bitwise xor
print(~3)           # Bitwise not
print(4 >> 2)       # Right Shift
print(4 << 2)       # Left Shift

# Membership Operator       in/not in
print('W' in 'West')
print(1 not in [2,3,4])